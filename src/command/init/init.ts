import type { Harness } from '../../harness/harness.js';
import { opencodeHarness } from '../../harness/opencode/opencode-harness.js';

export interface InitOptions {
  readonly targetDir: string;
  readonly harness?: Harness;
}

export interface InitResult {
  readonly writtenFiles: readonly string[];
}

const DEFAULT_SKILL_NAME = 'example';

const DEFAULT_SKILL_CONTENT = `---
name: example
description: Example skill generated by agkit.
---

# Example Skill

Replace this template with your project rules.
`;

export async function initProject(options: InitOptions): Promise<InitResult> {
  const harness = options.harness ?? opencodeHarness;
  const writtenPath = await harness.skills.write(
    options.targetDir,
    DEFAULT_SKILL_NAME,
    DEFAULT_SKILL_CONTENT,
  );

  return {
    writtenFiles: [writtenPath],
  };
}
